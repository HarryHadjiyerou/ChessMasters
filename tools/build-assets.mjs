// Builds the game-ready characters from "MESHY ASSETS\<LIGHT|DARK> - <PIECE> ANIMATION(S)\".
//  1. Picks the GLB with the most clips in each folder (source files are only read).
//  2. Repairs the knights' incomplete leg rigs (missing leg bones, re-weighted).
//  3. Gives custom rigs (rooks, knights) standard humanoid bone names.
//  4. Gives every character the clips its roles need (public/data/animations.json): its own
//     clip when it has one, otherwise one retargeted from another character.
//  5. Optimises (textures 1024/512 WebP, meshopt) into public/assets/pieces/<faction>_<piece>.glb
//     and writes public/assets/pieces.json plus docs/asset-report.md.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, prune, resample, textureCompress, meshopt, getBounds } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import sharp from 'sharp';
import { mapRig, repairLeg } from './rig.mjs';
import { describe, sampleSource, writeRetargeted, lockRoot, simpleIdle } from './retarget.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const projectDir = path.resolve(here, '..');
const sourceDir = path.resolve(projectDir, '..', 'MESHY ASSETS');
const outDir = path.join(projectDir, 'public', 'assets', 'pieces');
const manifestPath = path.join(projectDir, 'public', 'assets', 'pieces.json');
const reportPath = path.join(projectDir, 'docs', 'asset-report.md');
const roles = JSON.parse(fs.readFileSync(path.join(projectDir, 'public', 'data', 'animations.json'), 'utf8'));
const PIECE_CODE = { king: 'k', queen: 'q', rook: 'r', bishop: 'b', knight: 'n', pawn: 'p' };
const CENTAURS = new Set(['light_knight', 'dark_knight']);
// Leg repairs found by inspecting the knights' skin weights (see docs/asset-report.md).
const REPAIRS = {
  light_knight: [
    { name: 'br', parentName: 'Bone_006', select: (v, d) => (d === 'Bone_022' || d === 'Bone_023') && v.y < 0.55 },
  ],
  dark_knight: [
    { name: 'fl', parentName: 'Bone_004', select: (v, d) => d === 'Bone_004' && v.y < 0.38 && v.z > 0.15 && v.x > 0 },
    { name: 'fr', parentName: 'Bone_004', select: (v, d) => d === 'Bone_004' && v.y < 0.38 && v.z > 0.15 && v.x <= 0 },
  ],
};
// Attacks too, so a lunging clip can't carry the attacker into the defender's square.
const LOCKED_ROLES = ['idle', 'move', 'run', 'start', 'win', 'victory', 'attack'];

const io = new NodeIO()
  .registerExtensions(ALL_EXTENSIONS)
  .registerDependencies({ 'meshopt.encoder': MeshoptEncoder, 'meshopt.decoder': MeshoptDecoder });

const roleClips = (r) => Object.entries(r).filter(([k]) => k !== 'speed').flatMap(([, v]) => (Array.isArray(v) ? v : typeof v === 'string' ? [v] : []));

async function main() {
  await MeshoptEncoder.ready;
  await MeshoptDecoder.ready;
  fs.mkdirSync(outDir, { recursive: true });
  const report = ['# Asset report', '', `Generated by \`npm run assets\` on ${new Date().toISOString().slice(0, 10)}.`, ''];

  // 1. Load every character.
  const chars = {};
  for (const entry of fs.readdirSync(sourceDir, { withFileTypes: true })) {
    const m = entry.isDirectory() && entry.name.match(/^(LIGHT|DARK)\s*-\s*(\w+)\s+ANIMATIONS?$/i);
    if (!m) continue;
    const key = `${m[1].toLowerCase()}_${m[2].toLowerCase()}`;
    if (!PIECE_CODE[m[2].toLowerCase()]) { report.push(`- Unknown piece folder \`${entry.name}\`; skipped.`); continue; }
    let best = null;
    for (const f of fs.readdirSync(path.join(sourceDir, entry.name)).filter((x) => x.toLowerCase().endsWith('.glb'))) {
      const doc = await io.read(path.join(sourceDir, entry.name, f));
      const n = doc.getRoot().listAnimations().length;
      if (!best || n > best.n) best = { doc, file: f, n, folder: entry.name };
    }
    if (best) chars[key] = best;
  }

  // 2-3. Repair and name rigs.
  for (const [key, c] of Object.entries(chars)) {
    c.notes = [];
    for (const r of REPAIRS[key] ?? []) {
      const res = repairLeg(c.doc, r);
      c.notes.push(`Added leg \`${r.name}\`: joints ${res.joints.join(', ')}; re-weighted ${res.vertices} vertices.`);
    }
    const map = mapRig(c.doc, { centaur: CENTAURS.has(key) });
    if (!map.already) c.notes.push(`Custom rig mapped to standard names: ${map.mapped.join(', ')}.`);
    c.desc = describe(c.doc);
  }

  // 4a. Sample every source clip any character needs (before targets are modified).
  const exclude = new Set(roles.exclude);
  const index = new Map(); // clip name -> [character keys that have it natively]
  for (const [key, c] of Object.entries(chars)) for (const a of c.doc.getRoot().listAnimations()) {
    if (exclude.has(a.getName())) continue;
    index.set(a.getName(), [...(index.get(a.getName()) ?? []), key]);
  }
  const needed = Object.fromEntries(Object.entries(roles.pieces).map(([k, r]) => [k, [...new Set(roleClips(r))]]));
  const pickSource = (target, clip) => {
    const owners = index.get(clip) ?? [];
    if (owners.includes(target)) return target;
    return roles.preferredSource.find((s) => owners.includes(s)) ?? owners[0] ?? null;
  };
  const cache = new Map();
  for (const [target, clips] of Object.entries(needed)) for (const clip of clips) {
    const src = pickSource(target, clip);
    if (!src || src === target || cache.has(`${src}:${clip}`)) continue;
    const anim = chars[src].doc.getRoot().listAnimations().find((a) => a.getName() === clip);
    cache.set(`${src}:${clip}`, sampleSource(chars[src].desc, anim));
  }

  // 4b-5. Build each character.
  const pieces = [];
  for (const [key, c] of Object.entries(chars)) {
    const [faction, piece] = key.split('_');
    const r = roles.pieces[key];
    const want = new Set(needed[key] ?? []);
    const locked = new Set(r ? LOCKED_ROLES.flatMap((k) => (Array.isArray(r[k]) ? r[k] : r[k] ? [r[k]] : [])) : []);
    const native = [], retargeted = [], missing = [];
    for (const a of c.doc.getRoot().listAnimations()) {
      if (!want.has(a.getName())) { a.dispose(); continue; }
      if (locked.has(a.getName())) lockRoot(a);
      native.push(a.getName());
    }
    for (const clip of want) {
      if (native.includes(clip)) continue;
      if (clip === 'Idle_Simple') {
        // Generated: lower the arms; the pelvis bob is in metres, so no hip-height scaling.
        const idle = simpleIdle();
        idle.hipHeight = c.desc.hipHeight;
        writeRetargeted(c.doc, c.desc, idle, clip, { lockXZ: true });
        retargeted.push('Idle_Simple (generated)');
        continue;
      }
      const src = pickSource(key, clip);
      const sampled = src && cache.get(`${src}:${clip}`);
      if (!sampled) { missing.push(clip); continue; }
      writeRetargeted(c.doc, c.desc, sampled, clip, { lockXZ: locked.has(clip) });
      retargeted.push(`${clip} (from ${src})`);
    }
    const bounds = getBounds(c.doc.getRoot().getDefaultScene() ?? c.doc.getRoot().listScenes()[0]);
    const height = +(bounds.max[1] - bounds.min[1]).toFixed(4);
    await c.doc.transform(
      dedup(),
      prune({ keepLeaves: true }),
      resample({ tolerance: 0.0005 }),
      textureCompress({ encoder: sharp, targetFormat: 'webp', quality: 86, resize: [1024, 1024], slots: /baseColor/ }),
      textureCompress({ encoder: sharp, targetFormat: 'webp', quality: 82, resize: [512, 512], slots: /normal|metallicRoughness/ }),
      meshopt({ encoder: MeshoptEncoder, level: 'medium' }),
    );
    const bytes = await io.writeBinary(c.doc);
    fs.writeFileSync(path.join(outDir, `${key}.glb`), bytes);
    const clips = c.doc.getRoot().listAnimations().map((a) => a.getName());
    pieces.push({ faction, piece, file: `assets/pieces/${key}.glb`, height, centaur: CENTAURS.has(key), clips });
    report.push(`## ${key}`, '', `Source: \`${c.folder}\\${c.file}\` (${c.n} clips). Output ${(bytes.byteLength / 1048576).toFixed(2)} MB, bind height ${height}.`, '');
    for (const n of c.notes) report.push(`- ${n}`);
    report.push(`- Own clips used: ${native.join(', ') || 'none'}`);
    report.push(`- Retargeted: ${retargeted.join(', ') || 'none'}`);
    if (missing.length) report.push(`- **Missing (not in any file):** ${missing.join(', ')}`);
    report.push('');
    console.log(`${key}: ${(bytes.byteLength / 1048576).toFixed(2)} MB, ${native.length} own + ${retargeted.length} retargeted${missing.length ? `, MISSING ${missing.join(',')}` : ''}`);
  }
  fs.writeFileSync(manifestPath, JSON.stringify({ version: 2, pieces }, null, 2) + '\n');
  fs.writeFileSync(reportPath, report.join('\n') + '\n');
  console.log(`Wrote ${pieces.length} characters and ${path.relative(projectDir, manifestPath)}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
